-- =============================================================================
-- 0019_notification_delete.sql — 알림 개별 삭제
--
-- `backlog.md` §4 "알림 개별 삭제 — notifications에 delete 정책을 열어야 한다.
-- 마이그레이션 한 줄." 실제로 한 줄이다. 그 한 줄을 왜 0001이 안 열어 뒀는지,
-- 열고 나서 무엇이 달라지는지가 이 파일의 전부다.
--
-- 0001은 `notifications`에 select와 update만 두었다. 그때 알림은 **쌓기만 하고 아무도
-- 보지 않는** 상태였고(0015가 읽는 쪽을 만들기 전이다), 읽을 화면이 없으니 지울 화면도 없었다.
-- 정책을 안 연 것이 판단이었다기보다 쓸 자리가 없었다.
--
-- 0015가 목록을, 0018이 다섯 타입을 다 채우고 나니 지울 이유가 생긴다 — 특히 찜 알림처럼
-- 볼 일이 끝난 줄이 쌓인다. 알림 종류별 on/off(`backlog.md` §5-4)는 "앞으로 받지 않겠다"이고
-- 이것은 "이미 받은 것을 치우겠다"라서 서로를 대신하지 못한다.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 내 알림은 내가 지운다
--
-- `using`만 쓴다. delete에는 `with check`가 없다 — 지우고 나면 검사할 새 행이 없다.
--
-- update와 달리 **컬럼을 잠그는 트리거가 필요 없다.** 0015가 `guard_notification_update`를
-- 둔 것은 내 알림이면 payload까지 바꿀 수 있어서, 즉 남이 보낸 알림의 근거를 사후에
-- 바꿔치기할 수 있어서였다. 삭제에는 그런 어긋남이 없다 — 행이 통째로 사라질 뿐
-- 남는 행이 거짓말을 하게 되지 않는다.
--
-- 지운 뒤 되돌리는 길은 없다. 트리거는 그 사건이 일어난 순간에만 도므로(메시지·후기·댓글·찜)
-- 지나간 알림을 다시 만들어 낼 방법이 없다. 그래서 이것은 "안 보이게 하기"가 아니라
-- 진짜 삭제다 — 대신 화면이 한 번에 하나씩만 지우게 해서 실수의 크기를 줄인다.
-- (`is_read`를 보지 않는다. 안 읽은 알림도 지울 수 있다. 읽어야만 치울 수 있게 하면
--  볼 생각이 없는 알림을 굳이 열어 보게 만든다.)
-- -----------------------------------------------------------------------------
drop policy if exists notifications_delete on notifications;
create policy notifications_delete on notifications
  for delete
  using (auth.uid() = user_id);

-- -----------------------------------------------------------------------------
-- 2. 이 정책이 손대지 않는 것 둘
--
-- ① `purge_blocked_notifications`(0015 · 0018)는 `security definer`라 이 정책과 무관하게
--    돈다. 차단 청소가 지금까지 delete 정책 없이도 돌던 이유가 그것이다 — 함수 주인
--    권한으로 실행되어 RLS를 지나간다. 이 파일이 그 동작을 바꾸지 않는다.
--
-- ② Realtime은 여전히 insert만 흘린다(0015의 1번). 다른 기기에서 지운 알림이 이쪽 목록에서
--    즉시 사라지지는 않는다는 뜻이다. delete까지 구독하려면 `replica identity`를 손봐야 하고
--    (지운 행의 id를 실어 보내야 한다), 그 값에 비해 "다음에 열 때 없다"로 충분하다.
--    읽음 표시를 구독하지 않기로 한 것과 같은 판단이다.
-- -----------------------------------------------------------------------------

comment on table notifications is
  '내게 온 알림. 본인만 읽고(0001), 읽음 표시만 바꾸고(0015), 한 건씩 지울 수 있다(0019).';
